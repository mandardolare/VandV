def start_server():
    """ Start the TCP server to handle a single client sending multiple commands """
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as server_socket:
        server_socket.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)  # Allow fast restart
        server_socket.bind((HOST, PORT))
        server_socket.listen(1)  # Allow only ONE connection
        print(f"Server listening on {HOST}:{PORT}...")

        conn, addr = server_socket.accept()  # Accept only one client
        print(f"Connection established with {addr}")

        try:
            while True:
                command = conn.recv(4096)  # Receive command from the client
                if not command:
                    break  # If no command, client has disconnected

                print(f"Received command: {command.hex()}")
                responses = handle_command(command)

                for response in responses:
                    # conn.sedall(response)  # Send response to the client
                    conn.sendall(response)
                    print(f"Sent response: {response.hex()}")
                    time.sleep(0.1)  # Short delay between responses (if multiple)


        except ConnectionResetError:
            print("Client disconnected unexpectedly.")

        finally:
            print("Closing connection.")
            conn.close()  # Close the connection before restarting the server

if __name__ == "__main__":
    start_server()

